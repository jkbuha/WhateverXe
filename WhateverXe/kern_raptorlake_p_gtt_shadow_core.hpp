namespace RaptorLakeP {namespace GTTShadow {
constexpr size_t MMIOBytes=0x1000000,GuardBytes=4096,BufferBytes=MMIOBytes+2*GuardBytes;
constexpr size_t GTTOffset=0x800000,Entries=0x100000;
struct Patch {uint32_t offset,size;uint8_t before[10],after[10];};
// Preserve the firmware/stolen prefix. Initial dummy PTEs use one 64-bit
// store/readback, retaining the complete 39-bit address without LM bit1.
constexpr Patch Patches[]{
    {0x1024E,2,{0x77,0x4C},{0xEB,0x4C}},
    {0x102E8,4,{0x49,0xC1,0xEE,0x20},{0x49,0x83,0xCE,0x01}},
    {0x102EC,9,{0x47,0x89,0x74,0xCF,0x04,0x43,0x89,0x14,0xCF},{0x4F,0x89,0x34,0xCF,0x4B,0x8B,0x14,0xCF,0x90}},
    {0x10303,9,{0x45,0x89,0x74,0xC7,0x04,0x41,0x89,0x14,0xC7},{0x4D,0x89,0x34,0xC7,0x49,0x8B,0x14,0xC7,0x90}}
};
// Optional one-page constructor bound: 10MiB protected prefix + one 4KiB page.
constexpr Patch SlotLimit{0x1029C,10,{0x48,0xBE,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00},
    {0x48,0xBE,0x00,0x10,0xA0,0x00,0x00,0x00,0x00,0x00}};
inline bool exactSites(const void *image,size_t bytes) {
    if(!image || bytes<0x10312)return false;
    for(const auto &p:Patches)if(memcmp(static_cast<const uint8_t *>(image)+p.offset,p.before,p.size))return false;
    return true;
}
constexpr uint64_t prefixPTE(uint64_t stolen,size_t index){return (stolen+index*4096)|1;}
}}
