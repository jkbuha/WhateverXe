// Exact C004FC1A donor timing readout guard for physical Tiger Lake 9A49 rev1.
// Invalid clock ratios use the donor's existing empty-timing path.
#pragma once
#include <stdint.h>
#include <stddef.h>
#include <string.h>
namespace TGLTahoeTiming {
inline constexpr size_t entry=0x49D46, path=0x49D6F, empty=0x49DBD;
inline constexpr size_t site=0x4A00B, resume=0x4A024;
inline constexpr uint8_t timingHead[] {0x55,0x48,0x89,0xe5,0x41,0x57,0x41,0x56,0x41,0x55,0x41,0x54,0x53,0x50};
inline constexpr uint8_t timingPath[] {0x83,0xbe,0xd8,0x3f,0x00,0x00,0xff,0x74,0x17,0x48,0xff,0x05,0xe9,0x45,0x09,0x00,0x48,0xff,0x05,0x2a,0x74,0x09,0x00,0x48,0x81,0xc6,0x08,0x4a,0x00,0x00,0xeb,0x0e,0x48,0xff,0x05,0x22,0x74,0x09,0x00,0x48,0x81,0xc6,0xf0,0x49,0x00,0x00,0x4c,0x8b,0x26,0x4d,0x85,0xe4};
inline constexpr uint8_t timingEmpty[] {0x48,0xff,0x05,0x94,0x4a,0x09,0x00,0xbe,0xa0,0x00,0x00,0x00,0x4c,0x89,0xff};
inline constexpr uint8_t timingMath[] {0x41,0x8b,0x84,0x24,0x60,0x01,0x00,0x00,0x41,0x8b,0x8c,0x24,0x64,0x01,0x00,0x00,0x48,0x0f,0xaf,0xc3,0x31,0xd2,0x48,0xf7,0xf1};
inline bool requested(uint32_t identity,uint32_t revision,bool overridden,bool tahoe) {
 return identity==0x9A498086U && revision==1 && !overridden && tahoe;
}
inline bool matches(const uint8_t *base,size_t size,size_t symbolOffset) {
 return base && size>=resume+3 && symbolOffset==entry &&
  !memcmp(base+entry,timingHead,sizeof(timingHead)) &&
  !memcmp(base+path,timingPath,sizeof(timingPath)) &&
  !memcmp(base+empty,timingEmpty,sizeof(timingEmpty)) &&
  !memcmp(base+site,timingMath,sizeof(timingMath)) &&
  base[resume]==0x48 && base[resume+1]==0x89 && base[resume+2]==0xC1;
}
}
