#!/usr/bin/env python3
"""Generate kern_display13_dmc_fw.hpp from Intel's i915/adlp_dmc.bin (linux-firmware).

Container layout and checks follow Linux drivers/gpu/drm/i915/display/intel_dmc.c
(parse_dmc_fw_css / parse_dmc_fw_package / parse_dmc_fw_header, v3 DMC headers).
Selects, per dmc_id, the entry for stepping '*'/'*' (non-A0 parts such as RPL-P).
Usage: gen_dmc_header.py adlp_dmc.bin out.hpp
"""
import hashlib, struct, sys

MAX_MMIO = 20
MAIN_RANGE = (0x8F000, 0x8FFFF)
PIPE_RANGE = (0x5F000, 0x5FFFF)
LOAD_RANGE = {0: (0x80000, 0x86FFF), 1: (0x90000, 0x96FFF), 2: (0x98000, 0x9EFFF), 3: (0x52000, 0x53FFF), 4: (0x59000, 0x5AFFF)}
NAMES = {0: 'Main', 1: 'PipeA', 2: 'PipeB', 3: 'PipeC', 4: 'PipeD'}

def fail(msg):
    sys.exit('refused: ' + msg)

def parse(blob):
    if len(blob) < 128: fail('short CSS')
    css_len = struct.unpack_from('<I', blob, 4)[0] * 4
    if css_len != 128: fail(f'CSS header_len {css_len}')
    version = struct.unpack_from('<I', blob, 0x58)[0]
    pkg = css_len
    hlen, hver = blob[pkg], blob[pkg + 1]
    max_entries = {1: 20, 2: 32}.get(hver) or fail(f'package header_ver {hver}')
    pkg_len = hlen * 4
    if pkg_len != 16 + max_entries * 12: fail(f'package header_len {pkg_len}')
    n = struct.unpack_from('<I', blob, pkg + 12)[0]
    if n > max_entries: fail('num_entries')
    chosen = {}
    for i in range(n):
        e = pkg + 16 + i * 12
        dmc_id, step, sub = blob[e + 1], chr(blob[e + 2]), chr(blob[e + 3])
        offset = struct.unpack_from('<I', blob, e + 4)[0]
        if hver == 1: dmc_id = 0
        if step == '*' and sub == '*' and dmc_id not in chosen:
            chosen[dmc_id] = css_len + pkg_len + offset * 4
    if 0 not in chosen: fail('no */* main DMC entry')
    out = {}
    for dmc_id, h in sorted(chosen.items()):
        hlen, hver = blob[h + 4], blob[h + 5]
        if hver != 3: fail(f'dmc {dmc_id}: header_ver {hver} (only v3 expected for ADL-P)')
        if hlen * 4 != 256: fail(f'dmc {dmc_id}: header_len {hlen}')
        fw_size = struct.unpack_from('<I', blob, h + 12)[0]
        fw_version = struct.unpack_from('<I', blob, h + 16)[0]
        start = struct.unpack_from('<I', blob, h + 20)[0]
        count = struct.unpack_from('<I', blob, h + 92)[0]
        if not 1 <= count <= MAX_MMIO: fail(f'dmc {dmc_id}: mmio_count {count}')
        addrs = struct.unpack_from(f'<{count}I', blob, h + 96)
        datas = struct.unpack_from(f'<{count}I', blob, h + 176)
        lo, hi = MAIN_RANGE if dmc_id == 0 else PIPE_RANGE
        if any(not lo <= a <= hi for a in addrs): fail(f'dmc {dmc_id}: MMIO address out of range')
        llo, lhi = LOAD_RANGE[dmc_id]
        if not (llo <= start and start + fw_size * 4 - 1 <= lhi): fail(f'dmc {dmc_id}: load range')
        p = h + 256
        if not fw_size or p + fw_size * 4 > len(blob): fail(f'dmc {dmc_id}: payload truncated')
        payload = struct.unpack_from(f'<{fw_size}I', blob, p)
        out[dmc_id] = dict(start=start, version=fw_version, mmio=list(zip(addrs, datas)), payload=payload)
    return version, out

def emit(path, src_sha, version, dmcs):
    L = []
    L.append('// GENERATED by gen_dmc_header.py from linux-firmware i915/adlp_dmc.bin -- do not edit.')
    L.append(f'// Source sha256 {src_sha}. Intel DMC firmware, redistributed under the')
    L.append('// linux-firmware LICENSE.i915 terms (binary redistribution permitted, notice retained).')
    L.append('#ifndef KERN_DISPLAY13_DMC_FW_HPP\n#define KERN_DISPLAY13_DMC_FW_HPP\n#include <stdint.h>\nnamespace Display13DMCFirmware {')
    L.append(f'constexpr uint32_t PackageVersion=0x{version:08X};')
    L.append('struct MMIO {uint32_t reg,value;};')
    L.append('struct Program {uint32_t id,start,version,words;const uint32_t *payload;uint32_t mmioCount;const MMIO *mmio;};')
    for dmc_id, d in dmcs.items():
        n = NAMES[dmc_id]
        L.append(f'static const uint32_t {n}Payload[{len(d["payload"])}] {{')
        for i in range(0, len(d['payload']), 8):
            L.append('    ' + ','.join(f'0x{w:08X}' for w in d['payload'][i:i + 8]) + ',')
        L.append('};')
        L.append(f'static const MMIO {n}MMIO[{len(d["mmio"])}] {{' + ','.join(f'{{0x{a:05X},0x{v:08X}}}' for a, v in d['mmio']) + '};')
    L.append('static const Program programs[] {')
    for dmc_id, d in dmcs.items():
        n = NAMES[dmc_id]
        L.append(f'    {{{dmc_id},0x{d["start"]:05X},0x{d["version"]:08X},{len(d["payload"])},{n}Payload,{len(d["mmio"])},{n}MMIO}},')
    L.append('};\nconstexpr unsigned ProgramCount=sizeof(programs)/sizeof(programs[0]);\n}\n#endif\n')
    open(path, 'w').write('\n'.join(L))

if __name__ == '__main__':
    blob = open(sys.argv[1], 'rb').read()
    version, dmcs = parse(blob)
    emit(sys.argv[2], hashlib.sha256(blob).hexdigest(), version, dmcs)
    for i, d in dmcs.items():
        print(f'{NAMES[i]:<6} start 0x{d["start"]:05X} words {len(d["payload"]):5} version 0x{d["version"]:08X} mmio', ' '.join(f'{a:05X}={v:08X}' for a, v in d['mmio']))
    print(f'package version 0x{version:08X}')
